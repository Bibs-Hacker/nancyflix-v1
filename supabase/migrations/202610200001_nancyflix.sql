-- NANCYFLIX user-owned saved titles.
-- Run this migration in the Supabase SQL editor before using cloud watchlists.

create table if not exists public.watchlist (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id bigint not null,
  movie_data jsonb not null,
  created_at timestamptz not null default now(),
  constraint watchlist_user_movie_unique unique (user_id, movie_id)
);

create index if not exists watchlist_user_created_idx
  on public.watchlist (user_id, created_at desc);

alter table public.watchlist enable row level security;

revoke all on table public.watchlist from anon;
grant select, insert, update, delete on table public.watchlist to authenticated;
grant usage, select on sequence public.watchlist_id_seq to authenticated;

drop policy if exists "Users can view their own watchlist" on public.watchlist;
create policy "Users can view their own watchlist"
  on public.watchlist for select to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can add to their own watchlist" on public.watchlist;
create policy "Users can add to their own watchlist"
  on public.watchlist for insert to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update their own watchlist" on public.watchlist;
create policy "Users can update their own watchlist"
  on public.watchlist for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can remove from their own watchlist" on public.watchlist;
create policy "Users can remove from their own watchlist"
  on public.watchlist for delete to authenticated
  using ((select auth.uid()) = user_id);
